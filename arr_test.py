def show_list():
    # Число 1: Получено простым делением
    a: float = 0.1 + 0.2

    # Число 2: Получено из литерала
    b: float = 0.3

    # Примечание: Математически a должно быть равно b (0.1 + 0.2 = 0.3)

    # 🔬 Проверка на равенство
    is_equal = (a == b)

    print(f"Значение 'a' (0.1 + 0.2): {a:.18f}")  # Вывод: 0.300000000000000044
    print(f"Значение 'b' (0.3):          {b:.18f}")  # Вывод: 0.299999999999999989
    print(f"a == b: {is_equal}")

    rel_tol = 1e-9
    is_equal = (a - b < rel_tol)

    print(f"a == b: {is_equal}")


show_list()
